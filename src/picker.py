_JS = """
export default function(component) {
  const { data, setTriggerValue, parentElement } = component;
  const root = parentElement.querySelector('.gpl-pick');
  if (!root || !data) { return; }
  const input = root.querySelector('input');
  const list = root.querySelector('.list');
  const foot = root.querySelector('.foot');
  input.placeholder = data.placeholder || '';
  const items = data.items || [];
  const esc = (s) => String(s == null ? '' : s).replace(/[&<>"']/g,
      (c) => ({'&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;'}[c]));
  const norm = (s) => String(s || '').normalize('NFD').replace(/[\\u0300-\\u036f]/g, '').toLowerCase();
  const safeColor = (c) => (/^#[0-9a-fA-F]{6}$/.test(c || '') ? c : '#7b8494');
  const safeLogo = (u) => (/^data:image\\/png;base64,[A-Za-z0-9+/=]+$/.test(u || '') ? u : '');
  function render() {
    const q = norm(input.value.trim());
    const hits = items.filter((it) => !q || norm(it.name).includes(q) || norm(it.ticker).includes(q)
                                   || norm(it.sub).includes(q)).slice(0, data.max || 80);
    list.innerHTML = '';
    if (!hits.length) {
      const e = document.createElement('div'); e.className = 'empty'; e.textContent = data.empty || '';
      list.appendChild(e);
    }
    for (const it of hits) {
      const row = document.createElement('button');
      row.type = 'button';
      row.className = 'row' + (it.disabled ? ' dis' : '');
      row.setAttribute('role', 'option');
      const logo = safeLogo(it.logo);
      const tile = logo ? '<img alt="" src="' + logo + '">'
                        : '<span class="ini" style="background:' + safeColor(it.color) + '">' + esc(it.initials) + '</span>';
      row.innerHTML = '<span class="lg">' + tile + '</span><span class="tx"><span class="nm">' + esc(it.name)
        + '</span><span class="sb">' + esc(it.ticker) + ' · ' + esc(it.sub) + '</span></span>'
        + (it.badge ? '<span class="bd">' + esc(it.badge) + '</span>' : '')
        + '<span class="sw" style="background:' + safeColor(it.color) + '"></span>';
      if (!it.disabled) { row.addEventListener('click', () => setTriggerValue('picked', it.ticker)); }
      list.appendChild(row);
    }
    foot.textContent = String(data.count_text || '').replace('{n}', hits.length).replace('{total}', items.length);
  }
  input.oninput = render;
  render();
}
"""

_component = st.components.v2.component("gpl_logo_picker", html=_HTML, css=_CSS, js=_JS)
_HEX = re.compile(r"^#[0-9a-fA-F]{6}$")


def initials(name: str, ticker: str) -> str:
    words = [w for w in re.split(r"[^A-Za-z0-9]+", name or "") if w and w.lower() not in ("inc", "corp", "sa", "de",
                                                                                         "cv", "the", "plc", "ltd")]
    if len(words) >= 2:
        return (words[0][0] + words[1][0]).upper()
    base = (words[0] if words else ticker.lstrip("^")) or "?"
    return base[:2].upper()


def logo_picker(items: list[dict], key: str, placeholder: str, empty: str, count_text: str,
                max_rows: int = 80) -> str | None:
    """Render the picker; returns the ticker clicked in THIS run (None otherwise).

    ``items``: dicts with ticker, name, sub (market · currency), logo (data URI or None), color ('#rrggbb'),
    badge (short text, optional), disabled (bool, optional).
    """
    clean = []
    for it in items:
        clean.append({"ticker": str(it["ticker"]), "name": str(it.get("name") or it["ticker"]),
                      "sub": str(it.get("sub") or ""), "logo": it.get("logo") or "",
                      "color": it.get("color") if _HEX.match(str(it.get("color") or "")) else "",
                      "initials": initials(str(it.get("name") or ""), str(it["ticker"])),
                      "badge": str(it.get("badge") or ""), "disabled": bool(it.get("disabled"))})
    res = _component(key=key, data={"items": clean, "placeholder": placeholder, "empty": empty,
                                    "count_text": count_text, "max": max_rows},
                     on_picked_change=lambda: None)
    return getattr(res, "picked", None)
