"""Searchable security picker with logos (Streamlit custom component v2, no build step).

Each option shows a small logo tile before the company name, the ticker, market and currency, and a
swatch of the color the security uses in every chart.  Names come from the local database (they
were downloaded with each exact Yahoo ticker), so the picker only lists securities already stored.
All text is HTML-escaped in the browser; logos are base64 PNG data URIs generated by the app.
"""
